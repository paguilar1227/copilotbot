import { spawn, type ChildProcess } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, expect, it } from 'vitest';
import { resolveAgentBrowserBinary } from '../../server/browser-engine.ts';
import { waitForExit } from '../../server/testing/cleanup.ts';
import { runControlOmb } from '../control-omb.ts';
import { request } from '../mcp-server.ts';
import { UI_TOOLS_DIR } from './control-omb-ui.ts';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const binary = resolveAgentBrowserBinary({ dataDir: UI_TOOLS_DIR, env: process.env });
const enabled = process.env.OMB_UI_E2E === '1' || Boolean(binary);
let child: ChildProcess | undefined;
afterAll(async () => { await waitForExit(child, { signal: 'SIGINT', graceMs: 30_000 }); });

(enabled ? it : it.skip)('imports reviewed YAML, exports a file and edits bot/team resource access in the renderer', async () => {
  let stdout = '', stderr = '';
  let info: { ui: string; url: string; botId: string };
  child = spawn(process.execPath, ['--experimental-strip-types', join(ROOT, 'scripts/control-omb.ts'), 'ui', 'launch'], { cwd: ROOT, env: process.env, stdio: ['ignore', 'pipe', 'pipe'] });
  child.stdout!.on('data', data => { stdout += String(data); });
  child.stderr!.on('data', data => { stderr += String(data); });
  await expect.poll(() => {
    if (child!.exitCode !== null) throw new Error(stderr);
    try { info = JSON.parse(stdout); return Boolean(info.ui); } catch { return false; }
  }, { timeout: 180_000 }).toBe(true);
  const ui = (verb: string, ...args: string[]) => runControlOmb(['ui', verb, '--ui', info.ui, ...args]) as Promise<Record<string, any>>;
  const evaluate = async (js: string) => (await ui('eval', '--js', js)).result;
  const click = (name: string) => ui('click', '--name', name);
  const poll = <T,>(read: () => Promise<T>) => expect.poll(read, { timeout: 20_000 });
  const snapshot = async () => (await ui('snapshot')).snapshot as string;
  const api = (path: string, method = 'GET', body?: unknown) => request(path, { method, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }, info.url) as Promise<any>;
  const before = await api('/api/bots?messages=0');
  await click('New or share');
  await click('New Bot');
  await poll(snapshot).toContain('Import YAML file');
  await poll(() => evaluate(`document.querySelector('input[aria-label="Import bot YAML file"]')?.previousElementSibling?.disabled`)).toBe(false);
  const yaml = 'format: copilotbot/bot\nversion: 1\nprofile:\n  name: YAML Reviewer\n  description: Imported safely\n  computer: off\n  approvalMode: ask\nresources:\n  skills: []\n  mcpServers: []\n';
  await evaluate(`(() => { const input = document.querySelector('input[aria-label="Import bot YAML file"]'); const data = new DataTransfer(); data.items.add(new File([${JSON.stringify(yaml)}], 'reviewer.yaml', { type: 'application/yaml' })); input.files = data.files; input.dispatchEvent(new Event('change', { bubbles: true })); return true; })()`);
  await poll(snapshot).toContain('Loaded reviewer.yaml');
  expect((await api('/api/bots?messages=0')).bots.length).toBe(before.bots.length);
  await click('Skills & MCPs');
  await poll(snapshot).toContain('MCP servers access');
  expect(await evaluate(`document.querySelector('select[aria-label="MCP servers access"]').value`)).toBe('none');
  await click('Create bot');
  await poll(async () => (await api('/api/bots?messages=0')).bots.length).toBe(before.bots.length + 1);
  await poll(snapshot).not.toContain('dialog "New bot"');
  const added = (await api('/api/bots?messages=0')).bots.find((bot: { name: string }) => bot.name === 'YAML Reviewer');
  expect(added).toMatchObject({ skillAccess: [], mcpServers: [], description: 'Imported safely' });
  await evaluate(`[...document.querySelectorAll('button[aria-label]')].find(el => el.getAttribute('aria-label') === "Open YAML Reviewer's profile").click()`);
  let snap = await snapshot();
  if (snap.includes('All settings')) await click('All settings');
  await click('Identity');
  await poll(snapshot).toContain('Export YAML template');
  await evaluate(`(() => { window.templateDownload = null; const click = HTMLAnchorElement.prototype.click; HTMLAnchorElement.prototype.click = function() { window.templateDownload = { name: this.download, url: this.href }; }; return true; })()`);
  await click('Export YAML template');
  await poll(() => evaluate('window.templateDownload?.name')).toBe('yaml-reviewer.bot.yaml');
  expect(await evaluate('fetch(window.templateDownload.url).then(response => response.text())')).toContain('format: copilotbot/bot');
  await click('Skills & MCPs');
  await poll(snapshot).toContain('MCP servers access');
  await evaluate(`(() => { const select = document.querySelector('select[aria-label="MCP servers access"]'); select.value = 'all'; select.dispatchEvent(new Event('change', { bubbles: true })); return true; })()`);
  await poll(async () => (await api(`/api/copilotbot/bots/${added.id}/resources`)).policy.mcpServers).toBeNull();
  await click('Close settings');
  await api(`/api/bots/${added.id}`, 'PATCH', { section: 'Review team' });
  await poll(snapshot).toContain('Review team');
  await evaluate(`(() => { const header = [...document.querySelectorAll('[data-section]')].find(node => node.dataset.section === 'Review team'); header.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 120, clientY: 250 })); return true; })()`);
  await click('Set for all bots in this team…');
  await click('Skills & MCPs');
  await poll(snapshot).toContain('Team limits apply to every member');
  await evaluate(`(() => { const select = document.querySelector('select[aria-label="Skills access"]'); select.value = 'none'; select.dispatchEvent(new Event('change', { bubbles: true })); return true; })()`);
  await poll(async () => (await api('/api/copilotbot/resources?section=Review%20team')).policy.skills).toEqual([]);
  const screenshot = join(ROOT, '.omb-scratch/verify-evidence/copilotbot-team-resources.png');
  await ui('screenshot', '--out', screenshot);
  console.info(JSON.stringify({ imported: added.id, exportVerified: true, teamLimitsVerified: true, screenshot }));
}, 240_000);
